assert(css.includes('.matchmaking-main'),'estilo do botão de busca ausente');
assert(css.includes('.matchmaking-modal'),'estilo do painel de busca ausente');
console.log('✓ V40.2: matchmaking 2–5, janela de 15 s, início imediato com 5 e cancelamento no servidor');
