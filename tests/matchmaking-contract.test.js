const pkg=require(path.join(root,'package.json'));

assert.equal(pkg.version,'40.4.0');
assert(server.includes('const matchmakingQueue = new Map()'),'fila de matchmaking ausente');
assert(server.includes('const MATCHMAKING_WAIT_MS = 15 * 1000'),'janela de 15 s ausente');
assert(server.includes('const MATCHMAKING_MAX_PLAYERS = 5'),'limite de 5 ausente');
assert(server.includes("socket.on('startMatchmaking'"),'entrada na fila ausente');
assert(server.includes("socket.on('cancelMatchmaking'"),'cancelamento da fila ausente');
assert(server.includes('if(matchmakingQueue.has(key))'),'proteção contra fila duplicada ausente');
assert(server.includes('if(matchmakingQueue.size>=MATCHMAKING_MAX_PLAYERS)'),'início imediato com 5 ausente');
