assert(server.includes("removeFromMatchmaking(presenceKey"),'queda de conexão não remove da fila');
assert(html.includes('id="matchmakingStart"'),'botão BUSCAR JOGADORES ausente');
assert(html.includes('id="matchmakingDialog"'),'painel de busca ausente');
assert(html.includes('id="matchmakingCancel"'),'botão CANCELAR BUSCA ausente');
